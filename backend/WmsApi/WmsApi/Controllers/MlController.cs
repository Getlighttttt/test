using System.Net.Http.Json;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using WmsApi.Data;
using WmsApi.Models;

namespace WmsApi.Controllers
{
    // Bridge between the ASP.NET WMS and the Python ML service.
    [ApiController]
    [Route("api/ml")]
    public class MlController : ControllerBase
    {
        private readonly Db1Context _db;
        private readonly MovementLogger _logger;
        private readonly IHttpClientFactory _http;
        private readonly IConfiguration _config;

        public MlController(Db1Context db, MovementLogger logger, IHttpClientFactory http, IConfiguration config)
            => (_db, _logger, _http, _config) = (db, logger, http, config);

        // Python ML -> C#: create/update an alert and one open auto-replenishment request.
        [AllowAnonymous]
        [HttpPost("alerts")]
        public async Task<IActionResult> ReceiveAlert(MlAlertDto dto, [FromHeader(Name = "X-API-Key")] string? apiKey)
        {
            if (apiKey != (_config["Ml:ApiKey"] ?? "dev-ml-key"))
                return Unauthorized(new { message = "Invalid API key" });

            var lineName = ProductionLines.Normalize(dto.LineName);
            if (lineName == null)
                return BadRequest(new { message = "Production line must be L1 or L2" });

            var product = await _db.Products.FirstOrDefaultAsync(p => p.Code == dto.ProductCode);
            if (product == null)
                return NotFound(new { message = "Unknown product" });

            // Only one open alert for each product/production-line combination.
            var alert = await _db.Alerts.FirstOrDefaultAsync(a =>
                a.ProductId == product.Id && a.LineName == lineName && a.Status == "NEW");
            if (alert == null)
            {
                alert = new Alert { ProductId = product.Id, LineName = lineName };
                _db.Alerts.Add(alert);
            }
            alert.RiskPercent = dto.RiskPercent;
            alert.Message = dto.Message;
            alert.CreatedAt = DateTime.UtcNow;

            // Existing manual replenishment requests are not changed or restricted.
            var request = await _db.ReplenishmentRequests.FirstOrDefaultAsync(r =>
                r.ProductId == product.Id && r.LineName == lineName && r.AutoGenerated && r.Status != "DONE");
            if (request == null)
            {
                request = new ReplenishmentRequest
                {
                    ProductId = product.Id,
                    LineName = lineName,
                    Quantity = dto.RecommendedQty,
                    Priority = dto.Priority,
                    AutoGenerated = true
                };
                _db.ReplenishmentRequests.Add(request);
            }
            else
            {
                request.Quantity = Math.Max(request.Quantity, dto.RecommendedQty);
                request.Priority = Math.Min(request.Priority, dto.Priority);
            }

            await _db.SaveChangesAsync();
            await _logger.LogAsync("ML_ALERT", "", product.Code, dto.RecommendedQty,
                null, null, "ml-service", dto.Message, lineName: lineName);

            return Ok(new { alertId = alert.Id, replenishmentId = request.Id });
        }

        // C# -> dashboard: alerts from operational DB1.
        [Authorize(Roles = "Dispecer")]
        [HttpGet("alerts")]
        public async Task<IActionResult> GetAlerts()
        {
            var alerts = await _db.Alerts.Include(a => a.Product)
                .Where(a => a.Status == "NEW")
                .OrderByDescending(a => a.RiskPercent)
                .ToListAsync();

            return Ok(alerts.Select(a => new
            {
                id = a.Id,
                productCode = a.Product!.Code,
                productName = a.Product.Name,
                lineName = a.LineName,
                riskPercent = a.RiskPercent,
                message = a.Message,
                status = a.Status,
                createdAt = a.CreatedAt
            }));
        }

        [Authorize(Roles = "Dispecer")]
        [HttpPost("alerts/{id}/ack")]
        public async Task<IActionResult> AckAlert(int id)
        {
            var alert = await _db.Alerts.Include(a => a.Product)
                .FirstOrDefaultAsync(a => a.Id == id);
            if (alert == null)
                return NotFound(new { message = "Unknown alert" });

            alert.Status = "ACK";
            await _db.SaveChangesAsync();
            // Inform Python of the acknowledgment, while keeping the WMS operational if ML is down.
            using var response = await CallMl(HttpMethod.Post, "/api/alerts/ack",
                new { productCode = alert.Product!.Code, lineName = alert.LineName });

            return Ok(new { message = "Alert acknowledged" });
        }

        // Proxies for the existing authenticated WMS frontend.
        [Authorize(Roles = "Skladnik,Dispecer")]
        [HttpGet("risk")]
        public Task<IActionResult> Risk() => Proxy(HttpMethod.Get, "/api/predictions/latest");

        [Authorize(Roles = "Dispecer")]
        [HttpPost("forecast/run")]
        public Task<IActionResult> RunForecast() => Proxy(HttpMethod.Post, "/api/forecast/run");

        [Authorize(Roles = "Dispecer")]
        [HttpPost("train")]
        public Task<IActionResult> Train([FromQuery] string source = "auto")
            => Proxy(HttpMethod.Post, $"/api/model/train?source={Uri.EscapeDataString(source)}");

        [Authorize(Roles = "Dispecer")]
        [HttpPut("threshold")]
        public Task<IActionResult> SetThreshold(MlThresholdDto dto)
            => Proxy(HttpMethod.Put, "/api/model/threshold", new { criticalThreshold = dto.CriticalThreshold });

        private async Task<HttpResponseMessage?> CallMl(HttpMethod method, string path, object? body = null)
        {
            try
            {
                var client = _http.CreateClient("ml");
                using var msg = new HttpRequestMessage(method, path);
                if (body != null)
                    msg.Content = JsonContent.Create(body);
                return await client.SendAsync(msg);
            }
            catch (HttpRequestException)
            {
                return null;
            }
            catch (TaskCanceledException)
            {
                return null;
            }
        }

        private async Task<IActionResult> Proxy(HttpMethod method, string path, object? body = null)
        {
            using var response = await CallMl(method, path, body);
            if (response == null)
                return StatusCode(503, new { message = "ML service is unavailable" });

            var content = await response.Content.ReadAsStringAsync();
            return new ContentResult
            {
                Content = content,
                ContentType = "application/json",
                StatusCode = (int)response.StatusCode
            };
        }
    }
}
