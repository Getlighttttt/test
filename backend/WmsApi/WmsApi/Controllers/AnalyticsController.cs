using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using WmsApi.Data;
using WmsApi.Models;

namespace WmsApi.Controllers;

[ApiController]
[Route("api/analytics")]
[Authorize(Roles = "Dispecer")]
public class AnalyticsController : ControllerBase
{
    private readonly Db1Context _db1;
    private readonly Db2Context _db2;

    public AnalyticsController(Db1Context db1, Db2Context db2) => (_db1, _db2) = (db1, db2);

    [HttpGet("overview")]
    public async Task<IActionResult> Overview([FromQuery] int days = 30, [FromQuery] string consumptionPeriod = "7d")
    {
        if (days is not (7 or 30 or 90))
            return BadRequest(new { message = "Days must be 7, 30, or 90." });
        if (consumptionPeriod is not ("24h" or "7d" or "30d"))
            return BadRequest(new { message = "Consumption period must be 24h, 7d, or 30d." });

        var from = DateTime.UtcNow.AddDays(-days);
        var movements = await _db2.MovementLogs.AsNoTracking()
            .Where(x => x.Timestamp >= from)
            .Select(x => new { x.Timestamp, x.EventType, x.ProductCode, x.Quantity, x.LineName })
            .ToListAsync();
        // Synthetic rows are generated only to train/test the ML model. They are not
        // real warehouse activity and must never be presented as operational analytics.
        var syntheticConsumptionCount = await _db2.LineConsumptionLogs.AsNoTracking()
            .CountAsync(x => x.PeriodEnd >= from && x.Source == "synthetic");
        var consumption = await _db2.LineConsumptionLogs.AsNoTracking()
            .Where(x => x.PeriodEnd >= from && x.Source != "synthetic")
            .Select(x => new { x.PeriodEnd, x.ProductCode, x.LineName, x.QuantityConsumed, x.Unit })
            .ToListAsync();

        var pallets = await _db1.Pallets.AsNoTracking()
            .Where(p => p.Status != PalletStatus.WrittenOff && p.Status != PalletStatus.Consumed)
            .Select(p => new { p.Status, p.Quantity, ProductCode = p.Product!.Code })
            .ToListAsync();
        var requests = await _db1.ReplenishmentRequests.AsNoTracking()
            .Where(r => r.CreatedAt >= from)
            .Select(r => new { r.Status, r.AutoGenerated, r.CreatedAt })
            .ToListAsync();
        var openRequests = await _db1.ReplenishmentRequests.AsNoTracking()
            .CountAsync(r => r.Status != "DONE");
        var openDeviations = await _db1.Receipts.AsNoTracking()
            .CountAsync(r => r.Status == "WITH_DEVIATION");
        var openQuarantine = await _db1.QuarantineCases.AsNoTracking()
            .CountAsync(q => q.Status == "OPEN");

        // 7 days: daily buckets. 30/90 days: weekly buckets to keep the chart readable.
        var bucketDays = days == 7 ? 1 : 7;
        var bucketCount = (int)Math.Ceiling(days / (double)bucketDays);
        var periodStart = DateTime.UtcNow.Date.AddDays(-days + 1);
        var movementDays = Enumerable.Range(0, bucketCount).Select(i =>
        {
            var bucketStart = periodStart.AddDays(i * bucketDays);
            var bucketEnd = bucketStart.AddDays(bucketDays);
            if (bucketEnd > DateTime.UtcNow.Date.AddDays(1)) bucketEnd = DateTime.UtcNow.Date.AddDays(1);
            return new
            {
                date = bucketStart.ToString("yyyy-MM-dd"),
                label = bucketDays == 1 ? bucketStart.ToString("MMM d") : $"{bucketStart:MMM d}–{bucketEnd.AddDays(-1):MMM d}",
                received = movements.Where(m => m.Timestamp >= bucketStart && m.Timestamp < bucketEnd && m.EventType == "RECEIVE").Sum(m => m.Quantity),
                issued = movements.Where(m => m.Timestamp >= bucketStart && m.Timestamp < bucketEnd && m.EventType == "TO_LINE").Sum(m => m.Quantity),
                consumed = consumption.Where(c => c.PeriodEnd >= bucketStart && c.PeriodEnd < bucketEnd).Sum(c => c.QuantityConsumed)
            };
        }).ToList();

        var stockByZone = new[]
        {
            new { zone = "Storage", quantity = pallets.Count(p => p.Status == PalletStatus.Stored) },
            new { zone = "Production lines", quantity = pallets.Count(p => p.Status == PalletStatus.OnLine) },
            new { zone = "Receiving", quantity = pallets.Count(p => p.Status == PalletStatus.Received) },
            new { zone = "Quarantine", quantity = pallets.Count(p => p.Status == PalletStatus.Quarantine) },
            new { zone = "Rework / Claim", quantity = pallets.Count(p => p.Status == PalletStatus.Rework || p.Status == PalletStatus.Claim) }
        };

        var consumptionByLine = consumption.GroupBy(c => new { c.LineName, c.Unit })
            .Select(g => new { line = $"{g.Key.LineName} ({g.Key.Unit})", quantity = g.Sum(x => x.QuantityConsumed), unit = g.Key.Unit })
            .OrderBy(x => x.line).ToList();
        var topMaterials = consumption.GroupBy(c => new { c.ProductCode, c.Unit })
            .Select(g => new { productCode = g.Key.ProductCode, quantity = g.Sum(x => x.QuantityConsumed), unit = g.Key.Unit })
            .OrderByDescending(x => x.quantity).Take(5).ToList();

        // Consumption trend uses real, non-synthetic production records only.
        var consumptionHours = consumptionPeriod == "24h" ? 24 : consumptionPeriod == "7d" ? 24 * 7 : 24 * 30;
        var consumptionFrom = DateTime.UtcNow.AddHours(-consumptionHours);
        var trendRows = await _db2.LineConsumptionLogs.AsNoTracking()
            .Where(x => x.PeriodEnd >= consumptionFrom && x.Source != "synthetic")
            .Select(x => new { x.PeriodEnd, x.ProductCode, x.QuantityConsumed, x.Unit })
            .ToListAsync();
        var trendBucketHours = consumptionPeriod == "24h" ? 1 : 24;
        var trendBucketCount = (int)Math.Ceiling(consumptionHours / (double)trendBucketHours);
        var trendStart = consumptionPeriod == "24h"
            ? new DateTime(DateTime.UtcNow.Year, DateTime.UtcNow.Month, DateTime.UtcNow.Day, DateTime.UtcNow.Hour, 0, 0, DateTimeKind.Utc).AddHours(-23)
            : DateTime.UtcNow.Date.AddDays(-(consumptionPeriod == "7d" ? 6 : 29));
        var consumptionTrend = trendRows.GroupBy(x => new { x.ProductCode, x.Unit })
            .Select(g => new { productCode = g.Key.ProductCode, unit = g.Key.Unit, points = Enumerable.Range(0, trendBucketCount).Select(i => {
                var start = trendStart.AddHours(i * trendBucketHours);
                var end = start.AddHours(trendBucketHours);
                return new { label = consumptionPeriod == "24h" ? start.ToString("HH:mm") : start.ToString("MMM d"), timestamp = start, quantity = g.Where(x => x.PeriodEnd >= start && x.PeriodEnd < end).Sum(x => x.QuantityConsumed) };
            }).ToList() })
            .OrderBy(x => x.productCode).ToList();

        // Latest historical prediction per product/line, then highest material risk per line.
        var predictionRows = await _db2.PredictionHistories.AsNoTracking()
            .OrderByDescending(x => x.Timestamp)
            .Select(x => new { x.ProductCode, x.LineName, x.Timestamp, x.RiskPercent })
            .ToListAsync();
        var latestByMaterialLine = predictionRows.GroupBy(x => new { x.ProductCode, x.LineName })
            .Select(g => g.OrderByDescending(x => x.Timestamp).First());
        var shortageRiskByLine = latestByMaterialLine.GroupBy(x => x.LineName)
            .Select(g => new { lineName = g.Key, riskPercent = Math.Round(g.Max(x => x.RiskPercent), 1), materialsEvaluated = g.Count(), lastUpdated = g.Max(x => x.Timestamp) })
            .OrderBy(x => x.lineName).ToList();

        return Ok(new
        {
            periodDays = days,
            dataQuality = new { syntheticConsumptionExcluded = syntheticConsumptionCount },
            kpis = new
            {
                totalStock = pallets.Count,
                quarantinedStock = pallets.Count(p => p.Status == PalletStatus.Quarantine),
                consumptionRecords = consumption.Count,
                excludedSyntheticConsumptionRecords = syntheticConsumptionCount,
                movementEvents = movements.Count,
                openRequests,
                openDeviations,
                openQuarantine,
                completedRequests = requests.Count(r => r.Status == "DONE"),
                autoRequests = requests.Count(r => r.AutoGenerated)
            },
            stockByZone,
            inventoryOverview = new { totalActivePallets = pallets.Count, zones = stockByZone },
            consumptionTrend = new { period = consumptionPeriod, materials = consumptionTrend },
            shortageRiskByLine,
            movementDays,
            consumptionByLine,
            topMaterials,
            requestStats = new
            {
                total = requests.Count,
                completed = requests.Count(r => r.Status == "DONE"),
                pending = requests.Count(r => r.Status != "DONE"),
                autoGenerated = requests.Count(r => r.AutoGenerated)
            }
        });
    }
}
