using Microsoft.EntityFrameworkCore;
using WmsApi.Models;

namespace WmsApi.Data;

public static class MasterDataBootstrapper
{
    public static async Task EnsureAsync(Db1Context db)
    {
        // EnsureCreated does not evolve an existing database. These statements are
        // intentionally idempotent so existing installations gain the new fields/table.
        await db.Database.ExecuteSqlRawAsync(
            """ALTER TABLE "Products" ADD COLUMN IF NOT EXISTS "IsActive" boolean NOT NULL DEFAULT TRUE;""");

        await db.Database.ExecuteSqlRawAsync(
            """
            CREATE TABLE IF NOT EXISTS "ProductionLines" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "Code" character varying(32) NOT NULL,
                "Name" character varying(120) NOT NULL,
                "Location" character varying(160) NOT NULL DEFAULT '',
                "IsActive" boolean NOT NULL DEFAULT TRUE
            );
            """);
        await db.Database.ExecuteSqlRawAsync(
            """CREATE UNIQUE INDEX IF NOT EXISTS "IX_ProductionLines_Code" ON "ProductionLines" ("Code");""");

        if (!await db.ProductionLines.AnyAsync())
        {
            db.ProductionLines.AddRange(
                new ProductionLine { Code = "L1", Name = "Production Line 1", Location = "Production Hall 1" },
                new ProductionLine { Code = "L2", Name = "Production Line 2", Location = "Production Hall 2" }
            );
            await db.SaveChangesAsync();
        }
    }
}
